export function getHedgerowEnhancementMovement(
    baseline: HedgerowLabel,
    proposed: HedgerowLabel,
): HedgerowEnhancementMovement {
    const baselineIndex = HEDGEROW_TYPES.indexOf(baseline);
    const proposedIndex = HEDGEROW_TYPES.indexOf(proposed);
    return MOVEMENTS[baselineIndex]![proposedIndex]!;
}
